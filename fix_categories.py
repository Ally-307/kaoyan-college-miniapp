DEFAULT = ['工学', '理学', '管理学', '文学', '经济学']
def get_cats(name, max_c):
    for pat, cats in RULES:
        if re.search(pat, name):
            r = cats[:max_c]
            while len(r) < max_c:
                for c in DEFAULT:
                    if c not in r: r.append(c)
                    if len(r) >= max_c: break
            return r
    return DEFAULT[:max_c]
