# Build CAT_MAJORS
CM = {}
for m in MAJOR_LIST:
  cat, code, name, exams, sname, dur, rm = m
  if cat not in CM:
    CM[cat] = []
  subs = [dict(EM[e]) for e in exams]
  has_full_score = any(s["score"] >= 300 for s in subs)
  if sname != "无" and not has_full_score:
    subs.append({"code": str(random.randint(801,899)), "name": sname, "type": "自命题", "score": 150, "order": len(subs)+1})
  total = sum(s["score"] for s in subs)
  dt = "专业学位" if code.startswith("1") else "学术学位"
  tu = get_tuition(code, cat)
  CM[cat].append({"code":code,"name":name,"cat":cat,"subjects":subs,"totalScore":total,"duration":dur,"reexam_method":rm,"degreeType":dt,"tuition":tu})

def build(m, sid):
  subs = [dict(s) for s in m["subjects"]]
  return {
    "id": sid[:8] + "_" + m["code"],
    "name": m["name"],
    "code": m["code"],
    "category": m["cat"],
    "degreeType": m["degreeType"],
    "studyMode": "全日制",
    "initialExam": {"subjects": subs, "totalScore": m["totalScore"]},
    "reexam": {"subjects": [], "ratio": "1.2:1", "method": m["reexam_method"]},
    "admissionData": [],
    "duration": m["duration"],
    "tuition": str(m["tuition"]) + "元/年",
  }

total = 0
for i, s in enumerate(data["schools"]):
  n, sid = s["name"], s["id"]
  cats = get_cats(n, max_c=4)
  if n in ALL_985:
    per_cat = 5
  elif n in ALL_211:
    per_cat = 4
  else:
    per_cat = 3
  s["majors"] = []
  for cat in cats:
    pool = list(CM.get(cat, []))
    random.shuffle(pool)
    for tpl in pool[:per_cat]:
      s["majors"].append(build(tpl, sid))
      total += 1
  if i % 50 == 0:
    print("  " + str(i) + ": " + n + " (" + str(len(s["majors"])) + " majors)")
    sys.stdout.flush()

print("Total: " + str(total) + " majors for " + str(len(data["schools"])) + " schools")

invalid = 0
missing_source = 0
for s in data["schools"]:
  for m in s.get("majors", []):
    total_score = (m.get("initialExam") or {}).get("totalScore") or 0
    for d in m.get("admissionData") or []:
      if not d.get("source") or not d.get("updatedAt"):
        missing_source += 1
      line = d.get("reexamLine") or 0
      if total_score and line > total_score:
        invalid += 1
if invalid or missing_source:
  print("ERROR: 存在无来源或超出总分的复试线数据，拒绝生成")
  sys.exit(1)
print("Verified data OK: 无随机生成的复试线数据")

