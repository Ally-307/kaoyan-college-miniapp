# 构建索引
CAT_MAJORS = {}
for cat, majors in MAJOR_TEMPLATES.items():
    lst = []
    for m in majors:
        code, name, _, exams, self_name, duration, reexam = m
        subjects_list = [dict(EXAM[e]) for e in exams]
        if self_name != "无" and not any(s["score"] >= 300 for s in subjects_list):
            subjects_list.append({"code": str(random.randint(801,899)), "name": self_name, "type": "自命题", "score": 150, "order": len(subjects_list)+1})
        total = sum(s["score"] for s in subjects_list)
        degree_type = "专业学位" if code.startswith("1") else "学术学位"
        tuition = get_tuition(code, cat)
        lst.append({
            "code": code, "name": name, "cat": cat,
            "subjects": subjects_list, "totalScore": total,
            "duration": duration, "reexam_method": reexam,
            "degreeType": degree_type, "tuition": tuition,
        })
    CAT_MAJORS[cat] = lst

def build_major(tpl, sid):
    subjects = [dict(s) for s in tpl["subjects"]]
    return {
        "id": sid[:8] + "_" + tpl["code"],
        "name": tpl["name"],
        "code": tpl["code"],
        "category": tpl["cat"],
        "degreeType": tpl["degreeType"],
        "studyMode": "全日制",
        "initialExam": {"subjects": subjects, "totalScore": tpl["totalScore"]},
        "reexam": {"subjects": [], "ratio": "1.2:1", "method": tpl["reexam_method"]},
        "admissionData": [],
        "duration": tpl["duration"],
        "tuition": str(tpl["tuition"]) + "元/年",
    }

# 主流程
count = 0
for s in data["schools"]:
    n, sid = s["name"], s["id"]
    if n in ALL_985:
        cats = get_cats(n, max_c=6)
        per_cat = 5
    elif n in ALL_211:
        cats = get_cats(n, max_c=5)
        per_cat = 4
    else:
        cats = get_cats(n, max_c=4)
        per_cat = 3
    s["majors"] = []
    for cat in cats:
        pool = CAT_MAJORS.get(cat, [])
        random.shuffle(pool)
        for tpl in pool[:per_cat]:
            s["majors"].append(build_major(tpl, sid))
            count += 1

print("Total majors: " + str(count) + " for " + str(len(data["schools"])) + " schools")

