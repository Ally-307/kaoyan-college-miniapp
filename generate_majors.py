def build_major(cat, tpl, school_name):
    code, name, exam_codes, exam_names = tpl
    subjects = []
    for i in range(len(exam_codes)):
        subjects.append({'code': exam_codes[i], 'name': exam_names[i], 'type': '统考', 'score': 100 if i < 2 else 150, 'order': i+1})
    # Add self-designed subject
    self_name = SELF_SUBJECTS.get(name, name + '专业综合')
    self_code = '8' + code[1:4] if code.startswith('0') else code
    subjects.append({'code': self_code, 'name': self_name, 'type': '自命题', 'score': 150, 'order': len(exam_codes)+1})
    
    return {
        'id': school_name[:10] + '_' + code,
        'name': name, 'code': code, 'category': cat,
        'degreeType': '专业学位' if code.startswith('08') or code.startswith('12') or code.startswith('04') or code.startswith('09') or code.startswith('10') or code.startswith('13') else '学术学位',
        'studyMode': '全日制',
        'initialExam': {'subjects': subjects, 'totalScore': 500},
        'reexam': {'ratio': '1.2:1', 'method': '面试'},
        'admissionData': [
            {'year': 2026, 'reexamLine': 263, 'admissionCount': 20, 'applicationCount': 80},
            {'year': 2025, 'reexamLine': 260, 'admissionCount': 18, 'applicationCount': 75},
        ],
        'duration': '3年', 'tuition': '8000元/年',
    }

