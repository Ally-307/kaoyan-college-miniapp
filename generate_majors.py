total_majors = 0
for school in data['schools']:
    school['majors'] = []
    name = school['name']
    cat_count = 3 if is_985(name) else (2 if is_211(name) else 1)
    # Pick categories based on school name hash for deterministic variety
    cats = list(MAJORS.keys())
    h = sum(ord(c) for c in name)
    chosen = [cats[(h + i) % len(cats)] for i in range(cat_count)]
    for cat in chosen:
        tpls = MAJORS[cat][:3]
        for tpl in tpls:
            major = build_major(cat, tpl, name)
            school['majors'].append(major)
            total_majors += 1

print(f'Generated {total_majors} majors for {len([s for s in data['schools'] if s['majors']])} schools')

